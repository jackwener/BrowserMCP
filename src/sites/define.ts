/**
 * Shared adapter definition validation and module rendering. tools.define creates an inactive draft;
 * activation moves the verified module into the user adapter source.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { USER_ADAPTERS_DIR } from '../lib/sources.js';

import type { Arg } from '@jackwener/browsermcp/adapter-sdk';
import { validateArgDefinitions } from './schema.js';
export type { Arg } from '@jackwener/browsermcp/adapter-sdk';

export interface ToolDefinition {
  site: string;
  name: string;
  description: string;
  access: 'read' | 'write';
  domain?: string;
  result?: { kind: 'rows' | 'value'; description: string; fields?: Record<string, string>; paginated?: boolean };
  args?: Arg[];
  /** JS source of the adapter body: `async ({ tab, args, sites, recon }) => …` */
  func: string;
}

const NAME_RE = /^[a-z0-9][a-z0-9-]{0,63}$/;

export function validateDefinition(def: ToolDefinition): void {
  if (!NAME_RE.test(def.site) || !NAME_RE.test(def.name)) throw Object.assign(new Error('site and name must match /^[a-z0-9][a-z0-9-]{0,63}$/'), { code: 'invalid_definition' });
  if (!def.description) throw Object.assign(new Error('description is required'), { code: 'invalid_definition' });
  if (def.access !== 'read' && def.access !== 'write') throw Object.assign(new Error("access must be 'read' or 'write'"), { code: 'invalid_definition' });
  if (def.result && (!['rows', 'value'].includes(def.result.kind) || !def.result.description?.trim() || def.result.fields !== undefined && (!def.result.fields || typeof def.result.fields !== 'object' || Object.values(def.result.fields).some((v) => typeof v !== 'string')) || def.result.paginated && def.result.kind !== 'rows')) throw Object.assign(new Error('result needs kind rows|value and a description; fields must be text and paginated applies to rows'), { code: 'invalid_definition' });
  if (!def.func) throw Object.assign(new Error('provide `func` source (async ({ tab, args }) => …)'), { code: 'invalid_definition' });
  try { validateArgDefinitions(def.args); } catch (err) { throw Object.assign(new Error((err as Error).message), { code: 'invalid_definition' }); }
  if (!/^\s*(async\s*)?(\(|[A-Za-z_$])/.test(def.func)) throw Object.assign(new Error('func must be a function expression such as `async ({ tab, args }) => { … }`'), { code: 'invalid_definition' });
  try { new Function(`return (${def.func});`); } catch (err) { throw Object.assign(new Error(`func does not parse: ${(err as Error).message}`), { code: 'invalid_definition' }); }
}

/** Ensure the user source dir can resolve the SDK subpath of this browsermcp installation. */
export function ensureUserSource(): string {
  fs.mkdirSync(USER_ADAPTERS_DIR, { recursive: true });
  const home = path.dirname(USER_ADAPTERS_DIR); // ~/.opencli-mcp
  const nodeModules = path.join(home, 'node_modules');
  fs.mkdirSync(nodeModules, { recursive: true });
  const sdkDir = path.dirname(createRequire(import.meta.url).resolve('@jackwener/browsermcp/adapter-sdk'));
  const packageDir = path.dirname(sdkDir);
  // Old user adapters keep importing the SDK through its previous package name.
  for (const name of ['@jackwener/browsermcp', 'opencli-mcp']) {
    const link = path.join(nodeModules, name);
    fs.mkdirSync(path.dirname(link), { recursive: true });
    const existing = fs.lstatSync(link, { throwIfNoEntry: false });
    let current: string | null = null;
    try { current = fs.realpathSync(link); } catch { /* a dangling link needs replacement */ }
    if (current !== fs.realpathSync(packageDir)) {
      if (existing && !existing.isSymbolicLink()) throw new Error(`${link} exists and is not a symlink`);
      if (existing) fs.unlinkSync(link);
      fs.symlinkSync(packageDir, link, 'dir');
    }
  }
  const pkg = path.join(home, 'package.json');
  if (!fs.existsSync(pkg)) fs.writeFileSync(pkg, JSON.stringify({ name: 'browsermcp-user-adapters', private: true, type: 'module' }, null, 2));
  return USER_ADAPTERS_DIR;
}

export function renderAdapterModule(def: ToolDefinition): string {
  return [
    `// Generated by browsermcp tools.define on ${new Date().toISOString()}`,
    `import { defineAdapter } from '@jackwener/browsermcp/adapter-sdk';`,
    ``,
    `export default defineAdapter({`,
    `  description: ${JSON.stringify(def.description)},`,
    `  access: ${JSON.stringify(def.access)},`,
    def.domain ? `  domain: ${JSON.stringify(def.domain)},` : null,
    def.result ? `  result: ${JSON.stringify(def.result)},` : null,
    `  args: ${JSON.stringify(def.args ?? [], null, 2).replace(/\n/g, '\n  ')},`,
    `  run: ${def.func.trim()},`,
    `});`,
    ``,
  ].filter((l): l is string => l !== null).join('\n');
}

export function deleteTool(site: string, name: string): boolean {
  const file = path.join(USER_ADAPTERS_DIR, site, `${name}.js`);
  if (!fs.existsSync(file)) return false;
  fs.rmSync(file);
  return true;
}

export function listDefinedTools(): Array<{ site: string; name: string; file: string }> {
  if (!fs.existsSync(USER_ADAPTERS_DIR)) return [];
  const out: Array<{ site: string; name: string; file: string }> = [];
  for (const site of fs.readdirSync(USER_ADAPTERS_DIR)) {
    const d = path.join(USER_ADAPTERS_DIR, site);
    try { if (!fs.statSync(d).isDirectory()) continue; } catch { continue; }
    for (const f of fs.readdirSync(d)) if (f.endsWith('.js') && !f.startsWith('_')) out.push({ site, name: f.replace(/\.js$/, ''), file: path.join(d, f) });
  }
  return out;
}
