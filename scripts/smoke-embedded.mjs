import { app, BrowserWindow, session as electronSession } from 'electron';
import assert from 'node:assert/strict';
import path from 'node:path';
import { readFileSync } from 'node:fs';
import http from 'node:http';
import { Client, InMemoryTransport } from '@modelcontextprotocol/client';
const { createEmbeddedBrowser } = await import(process.env.BROWSERMCP_SMOKE_SDK ?? '../dist/src/embedded/index.js');

const root = process.env.BROWSERMCP_SMOKE_ROOT;
app.on('window-all-closed', () => {});
const windows = new Set();
const clients = [];
let service, server;
const deadline = setTimeout(() => { console.error('Embedded smoke timed out'); app.exit(1); }, 60000);
try {
  await app.whenReady();
  server = http.createServer((req, res) => { if (req.url === '/api') { res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify({verified:true})); return; } if (req.url === '/frame') { res.setHeader('Content-Type', 'text/html'); res.end('<label>Child<input aria-label="Child"></label>'); return; } res.setHeader('Content-Type', 'text/html'); res.end('<!doctype html><title>Embedded fixture</title><label>Name<input aria-label="Name"></label><button onclick="document.querySelector(\'#result\').textContent=document.querySelector(\'input\').value">Save</button><p id="result">Empty</p><iframe src="/frame"></iframe>'); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}/`;
  const profile = scope => electronSession.fromPartition(`persist:${scope.profileId}`);
  const createPage = async scope => {
    const window = new BrowserWindow({ show: false, webPreferences: { session: profile(scope), contextIsolation: true, sandbox: true, nodeIntegration: false } });
    windows.add(window); window.once('closed', () => windows.delete(window));
    return window.webContents;
  };
  service = await createEmbeddedBrowser({ dataDir: path.join(root, 'data'), execution: 'trusted-node', browser: { createPage: async scope => { const contents = await createPage(scope); const window = BrowserWindow.fromWebContents(contents); return { contents, close: async () => { if (!window.isDestroyed()) window.destroy(); } }; }, profile } });
  const connect = async profileId => {
    const handle = service.createSession({ workspaceId: 'workspace', profileId });
    const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
    const client = new Client({ name: profileId, version: '1' });
    await handle.server.connect(serverTransport); await client.connect(clientTransport); clients.push(client);
    const js = async code => {
      if (process.env.BROWSERMCP_SMOKE_TRACE) console.log(profileId, code.slice(0, 120));
      const result = await client.callTool({ name: 'js', arguments: { code } });
      if (process.env.BROWSERMCP_SMOKE_TRACE) console.log(profileId, 'completed');
      const body = JSON.parse(result.content[0].text);
      assert.equal(result.isError ?? false, false, JSON.stringify(body));
      return body.value;
    };
    return { handle, client, js };
  };
  const hostEvents = [];
  const unsubscribe = service.subscribe(event => hostEvents.push(event));
  const a = await connect('alpha'), b = await connect('beta');
  assert.equal(a.client.getServerVersion().version, JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version);
  console.log('smoke: connected');
  await a.js('let events = await browser.chrome.watch("tabs.onCreated")');
  await a.js(`let tab = await browser.tabs.new(${JSON.stringify(url)}); tab.id`);
  const observation = await a.js('await tab.observe()');
  assert.match(observation.state, /Name/);
  await a.js('await tab.act({action:"fill",target:{label:"Name"},value:"Electron works"})');
  await a.js('await tab.act({action:"click",target:{role:"button",name:"Save"}})');
  await a.js('await tab.expect({text:"Electron works"})');
  await a.js('await tab.act({action:"fill",target:{label:"Child",frame:0},value:"inside frame"})');
  assert.equal(await a.js(`await tab.evaluate(${JSON.stringify("document.querySelector('input').value")}, {frame:0})`), 'inside frame');
  assert.equal((await a.js('await events.read()')).entries.length, 1);
  assert.equal((await b.js('await browser.chrome.call("tabs.query", [{}])')).length, 0);
  await a.js(`await tab.evaluate("fetch('/api').then(r=>r.json())")`);
  const network = await a.js('await tab.network.read({limit:100})');
  assert.ok(network.entries.some(entry => entry.url.endsWith('/api') && entry.responsePreview?.includes('verified')));
  const image = await a.js('let shot = await tab.screenshot(); ({mimeType:shot.mimeType,length:shot.base64.length})');
  assert.ok(image.length > 100);
  const cookieArgs = JSON.stringify({ url, name: 'account', value: 'alpha' });
  await a.js(`await browser.chrome.call('cookies.set', [${cookieArgs}])`);
  assert.equal((await b.js(`await browser.chrome.call('cookies.getAll', [{url:${JSON.stringify(url)}}])`)).length, 0);
  await b.js(`let tab = await browser.tabs.new(${JSON.stringify(url)}); await browser.chrome.call('cookies.set',[{url:${JSON.stringify(url)},name:'account',value:'beta'}])`);
  const definition = { site: 'fixture', name: 'account', description: 'Read current profile account', access: 'read', func: 'async ({tab}) => ({account: await tab.evaluate("document.cookie")})' };
  const draft = await a.js(`await tools.define({...${JSON.stringify(definition)}, func: async ({tab}) => ({account: await tab.evaluate("document.cookie")})})`);
  await a.js(`await tools.try(${JSON.stringify(draft.draftId)}, {}, {path:'value.account',equals:'account=alpha'})`);
  await a.js(`await tools.activate(${JSON.stringify(draft.draftId)})`);
  assert.equal((await a.js('await sites.run("fixture","account",{})')).account, 'account=alpha');
  assert.equal((await b.js('await sites.run("fixture","account",{})')).account, 'account=beta');
  const changed = await a.js(`await tools.define(${JSON.stringify({ ...definition, func: 'async ({tab}) => ({account: await tab.evaluate("document.cookie"), revision: 2})' })})`);
  await a.js(`await tools.try(${JSON.stringify(changed.draftId)}, {}, {path:'value.revision',equals:2}); await tools.activate(${JSON.stringify(changed.draftId)})`);
  assert.equal((await b.js('await sites.run("fixture","account",{})')).revision, 2);
  // Real Chromium: malformed invocations must have no side effects and the same session recovers.
  await a.js('await tab.evaluate(() => {globalThis.contractEffects = 0})');
  for (const options of ['5', '{args:5}', '{arg:NaN}', '{arg:new Date()}', '{arg:()=>1}']) {
    await assert.rejects(a.js(`await tab.evaluate(n => {globalThis.contractEffects++; return n}, ${options})`));
  }
  assert.equal(await a.js('await tab.evaluate(() => globalThis.contractEffects)'), 0);
  assert.equal(await a.js('await tab.evaluate(n => {globalThis.contractEffects++; return n}, {arg:5})'), 5);
  assert.equal(await a.js('await tab.evaluate(() => globalThis.contractEffects)'), 1);
  assert.deepEqual(await a.js('await tab.evaluate(x=>x,{arg:{$remote:1,$function:"data"}})'), {$remote:1,$function:'data'});
  console.log('smoke: adapters and profiles verified');
  const userContents = await createPage({ workspaceId: 'workspace', profileId: 'alpha' });
  await userContents.loadURL(url);
  const scope = { workspaceId: 'workspace', profileId: 'alpha' };
  const userHandle = service.registerPage({ contents: userContents, scope, url, close: async () => BrowserWindow.fromWebContents(userContents).destroy() });
  service.setActivePage(scope, userHandle);
  assert.equal((await a.js('await browser.user.openTabs()')).items.find(tab => tab.active).url, url);
  await a.js('let borrowed = await browser.user.claimTab({active:true})');
  assert.equal(hostEvents.find(event => event.kind === 'tab_acquired' && event.page.handle === userHandle).sessionId, a.handle.id);
  assert.equal((await a.js('await browser.chrome.call("tabs.query", [{active:true}])')).length, 1);
  let lazyContents, loadCount = 0;
  const lazyHandle = service.registerPage({ scope, url: url + '?restored', title: 'Restored tab', load: async signal => {
    signal.throwIfAborted(); loadCount++;
    lazyContents = await createPage(scope); await lazyContents.loadURL(url + '?restored');
    return lazyContents;
  }, close: async () => { if (lazyContents) BrowserWindow.fromWebContents(lazyContents).destroy(); } });
  const logicalTabId = service.getPages(scope).find(page => page.handle === lazyHandle).tabId;
  assert.equal((await a.js('await browser.user.openTabs({query:"Restored"})')).matched, 1);
  const missing = await a.js('await browser.user.openTabs({query:"does-not-match"})');
  assert.equal(missing.matched, 0); assert.ok(missing.totalInScope > 0); assert.ok(missing.excluded.owned > 0);
  const urlSearch = await a.js(`await browser.user.openTabs({query:${JSON.stringify(url + '?restored')}})`);
  assert.equal(urlSearch.matched, 1);
  assert.equal(loadCount, 0);
  service.setActivePage(scope, lazyHandle);
  await a.js('let restored = await browser.user.claimTab({active:true}); await restored.observe()');
  assert.equal(loadCount, 1);
  assert.equal(service.getPages(scope).find(page => page.handle === lazyHandle).tabId, logicalTabId);
  await a.js('await restored.release()');
  assert.equal(hostEvents.find(event => event.kind === 'tab_released' && event.page.handle === lazyHandle).sessionId, a.handle.id);
  await a.js(`await browser.chrome.call('tabs.remove', [${logicalTabId}])`);
  assert.equal(service.getPages(scope).some(page => page.handle === lazyHandle), false);
  unsubscribe();
  await a.client.callTool({ name: 'session_finalize', arguments: {} });
  assert.equal(userContents.isDestroyed(), false);
  const doomed = await a.js(`let doomed = await browser.tabs.new(${JSON.stringify(url)}); (await browser.tabs.list()).find(item => item.id === doomed.id).tabId`);
  const target = [...windows].find(window => window.webContents !== userContents && !window.webContents.isDestroyed() && window.webContents.session === profile({ profileId: 'alpha' }));
  // Destroy the remaining agent-created page from the host, then verify stale handles fail.
  const doomedId = await a.js('doomed.id');
  service.unregisterPage(doomedId);
  const stale = await a.client.callTool({ name:'js', arguments:{ code:'await doomed.observe()' } });
  assert.equal(stale.isError, true);
  target?.destroy();
  const timeout = await a.client.callTool({ name:'js', arguments:{ code:'await new Promise(() => {})', timeoutMs: 30 } });
  assert.equal(timeout.isError, true);
  assert.equal((await b.js('await sites.run("fixture","account",{})')).account, 'account=beta');
  const c = await connect('regression');
  const regressionScope = { workspaceId: 'workspace', profileId: 'regression' };
  const brokenId = service.registerPage({ scope: regressionScope, url, title: 'Broken restore', close: async () => {}, load: async () => { throw new TypeError('Host restore failed'); } });
  const brokenTabId = service.getPages(regressionScope).find(page => page.handle === brokenId).tabId;
  const failedClaim = await c.client.callTool({ name: 'js', arguments: { code: `await browser.user.claimTab({tabId:${brokenTabId}})` } });
  assert.equal(failedClaim.isError, true);
  assert.match(failedClaim.content[0].text, /host_callback_failed/);
  assert.equal(service.getPages(regressionScope).find(page => page.handle === brokenId).sessionId, undefined);
  service.unregisterPage(brokenId);
  const resultId = await c.js(`let result = await browser.tabs.new(${JSON.stringify(url)}); result.id`);
  assert.ok((await c.js('await browser.tabs.list()')).some(tab => tab.id === resultId));
  assert.match(await c.js('String(result.url)'), /RemoteMethod/);
  assert.equal(await c.js('await result.url()'), url);
  const invalidKeep = await c.client.callTool({ name: 'session_finalize', arguments: { keep: [{ tab: 'result', status: 'deliverable' }] } });
  assert.equal(JSON.parse(invalidKeep.content[0].text).error.code, 'invalid_tab_id');
  assert.ok((await c.js('await browser.tabs.list()')).some(tab => tab.id === resultId));
  const oldExecution = service.getPages(regressionScope).find(page => page.handle === resultId).webContentsId;
  BrowserWindow.getAllWindows().find(window => window.webContents.id === oldExecution).destroy();
  assert.ok((await c.js('await browser.tabs.list()')).some(tab => tab.id === resultId && tab.lifecycle === 'dormant'));
  await c.js('await result.markDeliverable()');
  const replacement = await createPage(regressionScope); await replacement.loadURL(url);
  service.attachPage(resultId, replacement);
  assert.match((await c.js('await result.observe()')).state, /Name/);
  const keptResult = await c.client.callTool({ name: 'session_finalize', arguments: {} });
  assert.equal(keptResult.isError ?? false, false);
  assert.equal(replacement.isDestroyed(), false);
  assert.equal(service.getPages(regressionScope).find(page => page.handle === resultId).sessionId, undefined);
  let backgroundContents;
  const backgroundId = service.registerPage({ scope: regressionScope, url, title: 'Background duplicate',
    load: async () => { backgroundContents = await createPage(regressionScope); await backgroundContents.loadURL(url); return backgroundContents; },
    close: async () => { if (backgroundContents && !backgroundContents.isDestroyed()) BrowserWindow.fromWebContents(backgroundContents).destroy(); },
  });
  service.setActivePage(regressionScope, resultId);
  const backgroundTabId = service.getPages(regressionScope).find(page => page.handle === backgroundId).tabId;
  assert.equal((await c.js('await browser.user.openTabs()')).items.length, 2);
  await c.js(`let background = await browser.user.claimTab({tabId:${backgroundTabId}}); await background.observe()`);
  assert.equal(service.getPages(regressionScope).find(page => page.handle === resultId).active, true);
  assert.equal(service.getPages(regressionScope).find(page => page.handle === backgroundId).active, false);
  await c.js('await background.markHandoff()');
  const handoff = await c.client.callTool({ name: 'session_finalize', arguments: {} });
  assert.equal(handoff.isError ?? false, false);
  await c.handle.close();
  assert.ok(service.getPages(regressionScope).every(page => page.sessionId === undefined));
  for (const page of service.getPages(regressionScope)) service.unregisterPage(page.handle);
  for (const window of [...windows]) if (window.webContents.session === profile(regressionScope)) window.destroy();
  console.log('PASS #16: background duplicate claim, resource replacement, stable ownership, local proxy inspection, invalid keep without cleanup, deliverable and handoff');
  console.log('smoke: finalizing sessions');
  await a.handle.close(); await b.handle.close();
  console.log('smoke: sessions closed');
  assert.equal(windows.size, 1);
  console.log('PASS embedded MCP: observe/act/verify, frames, network bodies, screenshots, Chrome calls/events, profiles, adapter creation/update, revocation, timeout, user-tab preservation and cleanup');
} catch (error) {
  console.error(error.stack ?? error); process.exitCode = 1;
} finally {
  console.log('smoke: disposing service');
  for (const client of clients) await client.close().catch(() => {});
  await service?.dispose().catch(error => { console.error(error); process.exitCode = 1; });
  for (const window of windows) window.destroy();
  server?.closeAllConnections();
  await new Promise(resolve => server ? server.close(resolve) : resolve());
  // Chromium can still have profile writes in flight until app.exit. The parent runner removes root.
  clearTimeout(deadline);
  app.exit(process.exitCode ?? 0);
}
